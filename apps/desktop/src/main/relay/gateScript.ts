/**
 * The hook script a Relay leg's Claude Code runs on Stop, PreToolUse, PermissionRequest and
 * PostToolUse. It asks AgentMate (POST /relay-gate) what to answer, and prints the answer only if
 * it is one of the few shapes a relay ever gives. Anything that goes wrong prints nothing and exits
 * 0, which leaves Claude Code to do what it would have done without AgentMate.
 *
 * PostToolUse fires on every tool call, so the script leaves at once unless the session's armed
 * file exists (main creates it when the context guard is due); only a question's answer is always
 * reported.
 */
export interface GateScriptOptions {
  portFile: string;
  /** Folder of `<sessionId>` files, one per leg whose context guard is due. */
  armedDir: string;
}

/** Plans longer than this are cut, and a cut plan is never approved (it could not be echoed back). */
export const GATE_PLAN_LIMIT = 48 * 1024;

export function relayGateScriptSource({ portFile, armedDir }: GateScriptOptions): string {
  return String.raw`#!/usr/bin/env node
// Generated by AgentMate for Relay sessions. Best effort by design: any failure exits 0 quietly.
'use strict';
const fs = require('node:fs');
const http = require('node:http');
const path = require('node:path');

process.on('uncaughtException', () => process.exit(0));
process.on('unhandledRejection', () => process.exit(0));
setTimeout(() => process.exit(0), 5000).unref();

const PORT_FILE = ${JSON.stringify(portFile)};
const ARMED_DIR = ${JSON.stringify(armedDir)};
const PLAN_LIMIT = ${GATE_PLAN_LIMIT};
const sessionId = process.env.AGENTMATE_SESSION_ID;
if (!sessionId || !/^[A-Za-z0-9_-]{1,128}$/.test(sessionId)) process.exit(0);

function done(out) {
  if (!out) process.exit(0);
  process.stdout.write(out, () => process.exit(0));
}

function valid(reply, event, tool) {
  if (!reply || typeof reply !== 'object') return false;
  if (event === 'Stop') {
    return reply.decision === 'block' && typeof reply.reason === 'string' && reply.reason.length <= 4096 && Object.keys(reply).length === 2;
  }
  const out = reply.hookSpecificOutput;
  if (!out || typeof out !== 'object' || out.hookEventName !== event) return false;
  if (event === 'PermissionRequest') {
    const decision = out.decision;
    if (tool !== 'ExitPlanMode' || !decision || decision.behavior !== 'allow') return false;
    const modes = decision.updatedPermissions;
    if (!Array.isArray(modes) || modes.length !== 1) return false;
    const mode = modes[0];
    return mode && mode.type === 'setMode' && (mode.mode === 'auto' || mode.mode === 'acceptEdits') && mode.destination === 'session' && decision.updatedInput && typeof decision.updatedInput === 'object';
  }
  if (event === 'PostToolUse') {
    return typeof out.additionalContext === 'string' && out.additionalContext.length <= 2048;
  }
  return false;
}

let input = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => {
  input += chunk;
});
process.stdin.on('end', () => {
  let payload = {};
  try {
    payload = JSON.parse(input);
  } catch {}
  const event = payload.hook_event_name;
  const tool = typeof payload.tool_name === 'string' ? payload.tool_name : '';
  if (event === 'PostToolUse' && tool !== 'AskUserQuestion') {
    try {
      fs.accessSync(path.join(ARMED_DIR, sessionId));
    } catch {
      process.exit(0);
    }
  }
  let server;
  try {
    server = JSON.parse(fs.readFileSync(PORT_FILE, 'utf8'));
  } catch {
    process.exit(0);
  }
  if (!server || !server.port || !server.token) process.exit(0);

  let toolInput;
  let planTruncated = false;
  if (payload.tool_input && typeof payload.tool_input === 'object' && (tool === 'ExitPlanMode' || tool === 'AskUserQuestion')) {
    toolInput = Object.assign({}, payload.tool_input);
    if (typeof toolInput.plan === 'string' && toolInput.plan.length > PLAN_LIMIT) {
      toolInput.plan = toolInput.plan.slice(0, PLAN_LIMIT);
      planTruncated = true;
    }
  }
  const body = JSON.stringify({
    token: server.token,
    sessionId,
    event,
    tool,
    permissionMode: typeof payload.permission_mode === 'string' ? payload.permission_mode : undefined,
    stopHookActive: payload.stop_hook_active === true,
    transcriptPath: typeof payload.transcript_path === 'string' ? payload.transcript_path : undefined,
    toolInput,
    planTruncated,
  });
  const req = http.request(
    {
      host: '127.0.0.1',
      port: server.port,
      path: '/relay-gate',
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(body) },
      timeout: 3000,
    },
    (res) => {
      let data = '';
      res.setEncoding('utf8');
      res.on('data', (chunk) => {
        data += chunk;
      });
      res.on('end', () => {
        if (res.statusCode !== 200) return done('');
        let reply;
        try {
          reply = JSON.parse(data);
        } catch {
          return done('');
        }
        if (!valid(reply, event, tool)) return done('');
        // Echo the original, uncut input: what Claude Code compares an approval against.
        if (event === 'PermissionRequest') reply.hookSpecificOutput.decision.updatedInput = payload.tool_input;
        done(JSON.stringify(reply));
      });
    },
  );
  req.on('error', () => done(''));
  req.on('timeout', () => req.destroy());
  req.end(body);
});
`;
}
