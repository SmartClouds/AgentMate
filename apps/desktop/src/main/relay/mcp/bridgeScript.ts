/** The MCP server name the CLIs see. Underscores, so Codex's TOML keys need no quoting. */
export const RELAY_MCP_SERVER = 'agentmate_relay';
export const RELAY_MCP_SCRIPT = 'relay-mcp.cjs';

export const RELAY_MCP_TOOLS = [
  'current_leg',
  'context_status',
  'finish_leg',
  'list_tasks',
  'get_task',
  'propose_tasks',
] as const;
export type RelayMcpTool = (typeof RELAY_MCP_TOOLS)[number];

/**
 * The stdio MCP server a Relay leg's CLI starts. It has no dependencies and keeps no state: a CLI
 * may start it more than once in a session, and every answer comes from AgentMate (POST /relay),
 * which finds the leg by the AGENTMATE_SESSION_ID the terminal put in the environment.
 */
export function relayBridgeScriptSource({ portFile }: { portFile: string }): string {
  return String.raw`#!/usr/bin/env node
// Generated by AgentMate for Relay sessions. Lets the agent on a Relay task read the board, check
// its context budget, report the end of its session and propose task changes for the user to
// approve. Writes only protocol messages to stdout.
'use strict';

const fs = require('node:fs');
const http = require('node:http');
const readline = require('node:readline');

const PORT_FILE = ${JSON.stringify(portFile)};
const SESSION_ID = process.env.AGENTMATE_SESSION_ID || '';
const DEFAULT_PROTOCOL_VERSION = '2025-06-18';
const empty = { type: 'object', properties: {}, additionalProperties: false };

const TOOLS = [
  {
    name: 'current_leg',
    description:
      'The Relay task this session works on: its id, the session number, the context budget, the handoff file to write and the handoffs of the tasks it depends on.',
    inputSchema: empty,
  },
  {
    name: 'context_status',
    description:
      'How much of this session\'s context budget is used, and where AgentMate asks for a handoff. Call it when you are unsure whether to hand off.',
    inputSchema: empty,
  },
  {
    name: 'finish_leg',
    description:
      'Report that this session is finished. Write the handoff file first. AgentMate checks it is new and has all five sections, and tells you what to fix if not. Make this your very last action.',
    inputSchema: {
      type: 'object',
      properties: {
        outcome: { type: 'string', enum: ['done', 'continue', 'blocked'] },
        tests: { type: 'string', enum: ['passed', 'failed', 'not-run'] },
        summary: { type: 'string', description: 'One or two sentences on what this session did.' },
      },
      required: ['outcome', 'tests'],
      additionalProperties: false,
    },
  },
  {
    name: 'list_tasks',
    description: 'Every task on the Relay board with its status and dependencies.',
    inputSchema: empty,
  },
  {
    name: 'get_task',
    description: 'One task file and its handoff, by id (like T004).',
    inputSchema: {
      type: 'object',
      properties: { id: { type: 'string' } },
      required: ['id'],
      additionalProperties: false,
    },
  },
  {
    name: 'propose_tasks',
    description:
      'Propose tasks to add, change, split or remove, for work you found that the board does not cover. The user reviews the proposal in AgentMate; nothing changes until they apply it. Never propose changes to a task that is done.',
    inputSchema: {
      type: 'object',
      properties: {
        proposal: {
          type: 'object',
          description:
            'An object with summary (string) and the lists add, change, split and remove. A task in add has title, depends, estimate, goal, scope, acceptance (list) and testPlan.',
        },
      },
      required: ['proposal'],
      additionalProperties: false,
    },
  },
];

function send(message) {
  process.stdout.write(JSON.stringify(message) + '\n');
}

function textResult(text, isError) {
  return { content: [{ type: 'text', text: text }], isError: Boolean(isError) };
}

function readConnection() {
  try {
    const data = JSON.parse(fs.readFileSync(PORT_FILE, 'utf-8'));
    if (typeof data.port === 'number' && typeof data.token === 'string') return data;
  } catch {}
  return null;
}

function askAgentMate(tool, args) {
  return new Promise((resolve, reject) => {
    const connection = readConnection();
    if (!connection) {
      reject(new Error('AgentMate is not running.'));
      return;
    }
    const payload = JSON.stringify({ token: connection.token, sessionId: SESSION_ID, tool: tool, args: args });
    const request = http.request(
      {
        host: '127.0.0.1',
        port: connection.port,
        path: '/relay',
        method: 'POST',
        headers: { 'content-type': 'application/json', 'content-length': Buffer.byteLength(payload) },
        timeout: 10000,
      },
      (response) => {
        let data = '';
        response.setEncoding('utf-8');
        response.on('data', (chunk) => {
          data += chunk;
        });
        response.on('end', () => {
          try {
            resolve(JSON.parse(data));
          } catch {
            reject(new Error('AgentMate sent an answer this bridge cannot read.'));
          }
        });
      },
    );
    request.on('timeout', () => request.destroy(new Error('AgentMate did not answer in time.')));
    request.on('error', (error) =>
      reject(new Error(error.code === 'ECONNREFUSED' ? 'AgentMate is not running.' : error.message)),
    );
    request.end(payload);
  });
}

async function callTool(name, args) {
  if (!TOOLS.some((tool) => tool.name === name)) return null;
  if (!SESSION_ID) return textResult('This session was not started by AgentMate Relay.', true);
  const answer = await askAgentMate(name, args && typeof args === 'object' ? args : {});
  if (!answer || !answer.ok) return textResult((answer && answer.error) || 'AgentMate refused the request.', true);
  return textResult(typeof answer.text === 'string' ? answer.text : JSON.stringify(answer.data, null, 2), false);
}

async function handle(message) {
  if (!message || typeof message !== 'object') return;
  if (message.id === undefined || message.id === null) return;
  const id = message.id;
  const params = message.params || {};
  if (message.method === 'initialize') {
    const version =
      typeof params.protocolVersion === 'string' ? params.protocolVersion : DEFAULT_PROTOCOL_VERSION;
    send({
      jsonrpc: '2.0',
      id,
      result: {
        protocolVersion: version,
        capabilities: { tools: {} },
        serverInfo: { name: 'agentmate_relay', version: '1.0.0' },
      },
    });
    return;
  }
  if (message.method === 'ping') {
    send({ jsonrpc: '2.0', id, result: {} });
    return;
  }
  if (message.method === 'tools/list') {
    send({ jsonrpc: '2.0', id, result: { tools: TOOLS } });
    return;
  }
  if (message.method === 'tools/call') {
    let result;
    try {
      result = await callTool(params.name, params.arguments);
    } catch (error) {
      result = textResult(error instanceof Error ? error.message : 'Something went wrong.', true);
    }
    if (result === null) {
      send({ jsonrpc: '2.0', id, error: { code: -32602, message: 'Unknown tool: ' + String(params.name) } });
      return;
    }
    send({ jsonrpc: '2.0', id, result });
    return;
  }
  send({ jsonrpc: '2.0', id, error: { code: -32601, message: 'Method not found: ' + String(message.method) } });
}

let inFlight = 0;
let inputClosed = false;

function exitWhenIdle() {
  if (inputClosed && inFlight === 0) process.exit(0);
}

const lines = readline.createInterface({ input: process.stdin, terminal: false });
lines.on('line', (line) => {
  if (line.trim() === '') return;
  let message;
  try {
    message = JSON.parse(line);
  } catch {
    send({ jsonrpc: '2.0', id: null, error: { code: -32700, message: 'Parse error' } });
    return;
  }
  inFlight += 1;
  handle(message)
    .catch(() => {})
    .finally(() => {
      inFlight -= 1;
      exitWhenIdle();
    });
});
lines.on('close', () => {
  inputClosed = true;
  exitWhenIdle();
});
`;
}
