import { HEALTH_DEFAULT_PATH, HEALTH_MEDIA_TYPE, HEALTH_PROTOCOL } from './types.js';

/**
 * The Runova Health Protocol, written for the coding agent that will implement it in a
 * project. It is a document, not code, because it has to work for any stack: the user copies it
 * (or the setup prompt that embeds it) into whatever agent they use.
 *
 * It builds on the IETF draft "Health Check Response Format for HTTP APIs" so existing health
 * libraries fit, and adds the security rules an endpoint full of internal error detail needs.
 */

/** The environment variables a compliant server reads. Only hashes, never the secrets. */
export const HEALTH_ENV = {
  tokenHash: 'RUNOVA_HEALTH_TOKEN_SHA256',
  user: 'RUNOVA_HEALTH_USER',
  passwordHash: 'RUNOVA_HEALTH_PASSWORD_SHA256',
} as const;

