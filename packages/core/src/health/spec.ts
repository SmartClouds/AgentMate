const NODE_SKETCH = `import { createHash, timingSafeEqual } from 'node:crypto';

const sha256 = (value) => createHash('sha256').update(value, 'utf8').digest();

function authorized(req) {
  const expected = process.env.${HEALTH_ENV.tokenHash};
  const header = req.headers.authorization ?? '';
  if (!expected || !header.startsWith('Bearer ')) return false;
  const presented = sha256(header.slice('Bearer '.length).trim());
  const wanted = Buffer.from(expected, 'hex');
  return wanted.length === presented.length && timingSafeEqual(presented, wanted);
}

app.get('${HEALTH_DEFAULT_PATH}', healthRateLimit, async (req, res) => {
  res.set('Cache-Control', 'no-store');
  if (!authorized(req)) {
    res.set('WWW-Authenticate', 'Bearer realm="runova-health"');
    return res.status(401).end();
  }
  const report = await cachedHealthReport(); // runs every check in parallel, 2 s timeout each
  res.status(report.status === 'fail' ? 503 : 200).type('${HEALTH_MEDIA_TYPE}').send(report);
});`;

export function buildHealthSpecMarkdown(): string {
  return `# Runova Health Protocol (${HEALTH_PROTOCOL})

Runova polls one healthcheck endpoint per environment and server of a project. The endpoint reports every service the app depends on, says whether each one works, and gives the error details of any that do not, so a person or an AI can fix them. Because those details describe the inside of the system, the endpoint is private and authenticated.

## 1. Endpoint

- Method: \`GET\` only. Answer any other method with \`405\`.
- Path: \`${HEALTH_DEFAULT_PATH}\` unless the project already has a reason to use another one.
- Transport: HTTPS only in every environment that is reachable from a network. Plain HTTP is acceptable only on localhost during development.
- Never redirect. Runova does not follow redirects, so a redirect is reported as a broken healthcheck. This keeps its credentials from being sent anywhere else.
- Requests Runova sends carry \`Accept: ${HEALTH_MEDIA_TYPE}\` and \`User-Agent: Runova-Health/1\`.

## 2. Authentication

The endpoint must never answer without valid credentials. Runova supports two standard schemes. Implement the one the target is set to use (or both).

### Bearer key (default, RFC 6750)

- Runova sends \`Authorization: Bearer <key>\`. The key starts with \`rnh_\` and is generated by Runova.
- The server stores only the SHA-256 hash of the key, as lowercase hex, in the environment variable \`${HEALTH_ENV.tokenHash}\`. The plaintext key never goes into the code, the repository, the config files or the logs.
- To check a request: take the text after \`Bearer \`, hash it with SHA-256 (UTF-8 bytes), and compare the two hashes with a constant-time comparison.

### HTTP Basic (RFC 7617)

- Runova sends \`Authorization: Basic base64(user:password)\`.
- The server stores the username in \`${HEALTH_ENV.user}\` and the SHA-256 hash of the password, as lowercase hex, in \`${HEALTH_ENV.passwordHash}\`.
- Decode the header, split at the first colon, and compare both the username and the hashed password in constant time. Check both even when the first one is wrong, so the timing gives nothing away.

### Rules for both

- Constant-time comparison only: \`crypto.timingSafeEqual\` (Node), \`CryptographicOperations.FixedTimeEquals\` (.NET), \`hash_equals\` (PHP), \`hmac.compare_digest\` (Python), \`subtle.ConstantTimeCompare\` (Go).
- If the variable is not set, the endpoint is disabled: refuse every request.
- A missing, malformed or wrong credential gets exactly the same answer: \`401\` with \`WWW-Authenticate: Bearer realm="runova-health"\` (or \`Basic realm="runova-health"\`) and an empty body. Never say which part was wrong and never hint at which checks exist.
- Never accept the key in the query string or a cookie. Only the \`Authorization\` header.
- Do not write the \`Authorization\` header to access logs or error trackers. Mask it or skip this path in request logging.
- Rate-limit the endpoint to about 30 requests a minute per client IP and answer \`429\` above that. Count failed authentication attempts in the same limit.

## 3. Response

Status codes and headers:

- \`200\` when the overall status is \`pass\` or \`warn\`, \`503\` when it is \`fail\`.
- \`Content-Type: ${HEALTH_MEDIA_TYPE}\`
- \`Cache-Control: no-store\`

The body is a JSON object:

\`\`\`json
${EXAMPLE}
\`\`\`

Top level:

| Field | Required | Meaning |
| --- | --- | --- |
| \`status\` | yes | \`pass\`, \`warn\` or \`fail\`. The worst status of the checks that matter. |
| \`version\` | no | Public version of the service. |
| \`releaseId\` | no | The deployed build or commit, so an error can be matched to the code. |
| \`serviceId\`, \`description\` | no | Which service this is. |
| \`time\` | no | When the report was produced (ISO 8601). |
| \`output\` | no | Only when the whole service is failing: one line saying why. |
| \`checks\` | yes | One entry per service or dependency (below). |
| \`runova\` | yes | \`{ "protocol": "${HEALTH_PROTOCOL}", "environment": "...", "server": "..." }\` |

Each key in \`checks\` is \`component:measurement\`, such as \`postgres:connection\`, \`redis:ping\`, \`queue:depth\`, \`stripe:api\`, \`disk:free\` or \`migrations:pending\`. Its value is an array of one object per instance:

| Field | Required | Meaning |
| --- | --- | --- |
| \`status\` | yes | \`pass\`, \`warn\` or \`fail\`. |
| \`componentId\` | when there are several instances | Which instance. |
| \`componentType\` | no | \`datastore\`, \`system\`, \`component\` or \`http\`. |
| \`observedValue\`, \`observedUnit\` | no | The measurement, such as \`12\` and \`ms\`. |
| \`time\` | no | When this check last ran. |
| \`output\` | when not \`pass\` | The error message. |
| \`runova\` | when not \`pass\` | Error details, below. |

The \`runova\` object of a failing check helps the person or AI that fixes it:

| Field | Meaning |
| --- | --- |
| \`errorCode\` | The error's code or class, such as \`ECONNREFUSED\` or \`SqlException\`. |
| \`detail\` | What was attempted and what happened, in a few sentences. |
| \`stack\` | The stack trace, at most about 8 KB. |
| \`hint\` | What usually fixes it, when the code knows. |
| \`since\` | When this check started failing (ISO 8601), if the app tracks it. |

## 4. What to check

- Every dependency the app needs to serve requests: databases, caches, queues, object storage, search, mail, and the external APIs it calls.
- The app's own state where it can break: pending migrations, background workers or schedulers that stopped, certificates close to expiry, low disk space.
- Use \`warn\` for degraded but working (slow, nearly full, a non-critical dependency down) and \`fail\` for broken.
- Checks must be read-only and cheap. Never write data, send mail or charge anything to perform a check. Ping, \`SELECT 1\`, a HEAD request or a metadata call is enough.

## 5. Safety and performance

- Give every check its own timeout of 2 seconds or less and run them in parallel. A check that times out is \`fail\` with \`output\` saying so.
- Cache the whole report for about 5 seconds so repeated calls cannot overload a dependency.
- Responses must never include secrets: no environment variable values, passwords, keys, tokens, connection strings with credentials, session data or personal data of users. Strip the password out of a connection string before putting an error in \`output\`, \`detail\` or \`stack\`. Runova redacts what it can recognize, but the endpoint is the first line of defense.
- Catch every error inside the healthcheck. The endpoint itself must never crash or return an HTML error page.

## 6. Example (Node.js and Express)

\`\`\`js
${NODE_SKETCH}
\`\`\`

The same structure applies in any framework: authenticate first, then build the report from checks that run in parallel with timeouts, then answer with the status code that matches \`status\`.

## 7. Verify

- \`curl -i https://<host>${HEALTH_DEFAULT_PATH}\` returns \`401\` with an empty body.
- \`curl -i -H "Authorization: Bearer <key>" https://<host>${HEALTH_DEFAULT_PATH}\` returns \`200\` or \`503\` with a JSON report.
- Stop a dependency and the matching check turns \`fail\` with a useful \`output\`.
- Add a test for the authentication and for the report shape.
`;
}
